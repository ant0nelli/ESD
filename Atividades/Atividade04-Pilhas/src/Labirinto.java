    public void imprimir() {

        for (int i = 0; i < mapa.length; i++) {
            for (int j = 0; j < mapa[i].length; j++) {
                System.out.print(mapa[i][j]);
            }
            System.out.println();
        }
    }

    public boolean resolver(Stack<String> pilha) {

        String[] partes = pilha.peek().split(",");
        int linha = Integer.parseInt(partes[0]);
        int coluna = Integer.parseInt(partes[1]);
        

        // Encontrar caminho
        if (linha > -1 && linha < mapa.length && coluna > -1 && coluna < mapa[0].length) {
            // Cima
            if(mapa[linha - 1][coluna] == 'T'){
                System.out.println("Labirinto resolvido");
                return true;
            }            
            else if (mapa[linha - 1][coluna] == ' ') {
                mapa[--linha][coluna] = '-';
                pilha.push(linha-- + "," + coluna);
            }



            // Baixo
            else if(mapa[linha + 1][coluna] == 'T'){
                System.out.println("Labirinto resolvido");
                return true;
            }
            else if (mapa[linha + 1][coluna] == ' ') {
                mapa[++linha][coluna] = '-';
                pilha.push(linha++ + "," + coluna);
            }
            // Direita
            else if(mapa[linha][coluna + 1] == 'T'){
                System.out.println("Labirinto resolvido");
                return true;
            }
            else if (mapa[linha][coluna + 1] == ' ') {
                mapa[linha][++coluna] = '-';
                pilha.push(linha + "," + coluna++);
            }
            // Esquerda
            else if(mapa[linha][coluna - 1] == 'T'){
                System.out.println("Labirinto resolvido");
                return true;
            }
            else if (mapa[linha][coluna - 1] == ' ') {
                mapa[linha][--coluna] = '-';
                pilha.push(linha++ + "," + coluna--);
            } else {
                pilha.pop();

            }
        } else {
            pilha.pop();
        }
        return false;
    }

